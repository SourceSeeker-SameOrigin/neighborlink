const assert = require('node:assert/strict');
const { runtime } = require('../2026-11-09-remediation/page-fixture.cjs');

(async () => {
  const calls = [];
  let fail = false;
  const env = runtime(async (name, action, { communityId, offset }) => {
    assert.equal(name, 'content');
    assert.equal(action, 'listNotices');
    calls.push([communityId, offset]);
    if (fail) throw Error('读取失败');
    return { list: [{ _id: communityId + offset, createdAt: 1795000000000 }], nextOffset: offset + 1, hasMore: offset === 0 };
  });
  const user = env.app.globalData.user;
  const page = env.instance('miniprogram/notices/list/list.js');
  const ids = () => Array.from(page.data.list, item => item._id);
  user.communityId = 'A';
  await page.onShow();
  assert.deepEqual(ids(), ['A0']);
  page.onHide();
  user.communityId = 'B';
  fail = true;
  const returned = page.onShow();
  assert.deepEqual(ids(), []);
  assert.equal(page.data.loading, true);
  await returned;
  assert.equal(page.data.error, '读取失败');
  assert.equal(page.data.hasMore, false);
  assert.equal(page.data.offset, 0);
  await page.loadMore();
  assert.deepEqual(calls, [['A', 0], ['B', 0]]);
  fail = false;
  await page.load({ type: 'tap' });
  assert.deepEqual(ids(), ['B0']);
  fail = true;
  await page.loadMore();
  assert.deepEqual(ids(), ['B0']);
  assert.equal(page.data.offset, 1);
  assert.equal(page.data.hasMore, true);
  fail = false;
  await page.loadMore();
  assert.deepEqual(ids(), ['B0', 'B1']);
  await page.loadMore();
  assert.deepEqual(calls.slice(2), [['B', 0], ['B', 1], ['B', 1]]);
  await page.load();
  user.communityId = 'C';
  await page.loadMore();
  assert.deepEqual(ids(), ['C0']);
  assert.deepEqual(calls.at(-1), ['C', 0]);
  console.log('通过：换区返回、首屏失败与重试、分页失败与原页重试、末页和页内身份范围变化');
})().catch(error => { console.error(error); process.exitCode = 1; });
